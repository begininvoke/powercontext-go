func candidateEvidenceModels(specification []byte) ([]string, error) {
	encoded, err := yaml.YAMLToJSON(specification)
	if err != nil {
		return nil, err
	}
	type property struct {
		MaxItems *int `json:"maxItems"`
	}
	var document struct {
		Components struct {
			Schemas map[string]struct {
				Properties map[string]property `json:"properties"`
			} `json:"schemas"`
		} `json:"components"`
	}
	if err := json.Unmarshal(encoded, &document); err != nil {
		return nil, err
	}
	models := make([]string, 0, 6)
	for name, schema := range document.Components.Schemas {
		sources, sourcesOK := schema.Properties["source_refs"]
		artifacts, artifactsOK := schema.Properties["artifact_refs"]
		if !sourcesOK || !artifactsOK || sources.MaxItems == nil || artifacts.MaxItems == nil {
			continue
		}
		if *sources.MaxItems == maxCombinedCandidateEvidence &&
			*artifacts.MaxItems == maxCombinedCandidateEvidence {
			models = append(models, name)
		}
	}
	slices.Sort(models)
	return models, nil
}
