func validateCombinedCandidateEvidence(sourceReferences, artifactReferences int) error {
	if sourceReferences+artifactReferences <= maxCombinedCandidateEvidence {
		return nil
	}
	return &CombinedEvidenceLimitError{
		SourceReferences: sourceReferences, ArtifactReferences: artifactReferences,
	}
}

func validateArtifactCandidatePageContract(value ArtifactCandidatePage) error {
	for index := range value.Candidates {
		if err := ValidatePowerContextContract(value.Candidates[index]); err != nil {
			return err
		}
	}
	return nil
}

func validateGeneratedCandidateResponseContract(value GeneratedCandidateResponse) error {
	candidate, ok := value.Candidate.Get()
	if !ok {
		return nil
	}
	return ValidatePowerContextContract(candidate)
}
